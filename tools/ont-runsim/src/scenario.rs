//! Scenarios: what to simulate. Loaded from TOML or a built-in preset.
//!
//! ```toml
//! seed = 42
//! hours = 72.0              # simulated run length
//! speed = 60.0              # 60 simulated seconds per wall-clock second
//! content = "fake"          # or "replay" (bytes from an existing run)
//! timeline = "synthetic"    # or "profile" (timing recorded from a real run)
//! profile = "run.json"      # with timeline = "profile"
//! extend = "repeat-batches" # or "stretch", when hours differ from the profile
//!
//! [fake]
//! fill = "random"           # or "zero"
//! size_scale = 1.0          # multiply every file size
//!
//! [replay]
//! run = "/data/exp/sample/20240101_1200_1A_PAW12345_abcdef12"
//!
//! [synthetic]
//! batch_every = "10m"
//! pod5_batch = "500MB"
//! fastq_pass_batch = "40MB"
//! fastq_fail_batch = "5MB"
//! barcodes = 0
//!
//! [[runs]]
//! experiment = "exp1"
//! sample = "sample1"
//! position = "1A"           # optional
//! flow_cell = "PAW12345"    # optional, random otherwise
//! start_after = "0s"
//!
//! [faults]
//! abort_after = "3h"        # run stops without a final summary
//! rewrite_closed = 2        # closed batch files rewritten a minute later
//! late_files = 1            # files appearing after the final summary
//! ```

use std::path::{Path, PathBuf};

use serde::Deserialize;

use crate::units::{parse_duration, parse_size};
use crate::{Error, Result, io_err};

/// Where file content comes from.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum ContentMode {
    /// Generated bytes with the right names, sizes and places.
    #[default]
    Fake,
    /// Bytes copied from an existing run.
    Replay,
}

/// Where the timing comes from.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum TimelineMode {
    /// Generated MinKNOW-like timeline.
    #[default]
    Synthetic,
    /// Timeline recorded with `ont-runsim profile`.
    Profile,
}

/// How a profile is fitted to a different number of hours.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum Extend {
    /// Keep the batch rhythm; repeat (or cut) batches to fill the hours.
    #[default]
    RepeatBatches,
    /// Scale every time by the same factor.
    Stretch,
}

/// Fill for fake binary content.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum Fill {
    /// Pseudo-random bytes (incompressible, like real pod5).
    #[default]
    Random,
    /// Zero bytes (fast; compresses on some shares).
    Zero,
}

/// `[fake]`
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields, default)]
pub struct Fake {
    /// Fill for binary files.
    pub fill: Fill,
    /// Factor applied to every file size.
    pub size_scale: f64,
}

impl Default for Fake {
    fn default() -> Self {
        Self {
            fill: Fill::Random,
            size_scale: 1.0,
        }
    }
}

/// `[replay]`
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Replay {
    /// Existing run folder to take bytes from.
    pub run: PathBuf,
}

/// `[synthetic]`
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields, default)]
pub struct Synthetic {
    /// Time between batch files.
    pub batch_every: String,
    /// Size of one pod5 batch.
    pub pod5_batch: String,
    /// Size of one `fastq_pass` batch (`"0B"`: no basecalled output).
    pub fastq_pass_batch: String,
    /// Size of one `fastq_fail` batch.
    pub fastq_fail_batch: String,
    /// Number of barcodes (0: unbarcoded).
    pub barcodes: u32,
}

impl Default for Synthetic {
    fn default() -> Self {
        Self {
            batch_every: "10m".into(),
            pod5_batch: "500MB".into(),
            fastq_pass_batch: "40MB".into(),
            fastq_fail_batch: "5MB".into(),
            barcodes: 0,
        }
    }
}

/// `[[runs]]`
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct RunSpec {
    /// Experiment (protocol group) folder name.
    pub experiment: String,
    /// Sample folder name.
    pub sample: String,
    /// Flow cell position, e.g. `1A`.
    #[serde(default)]
    pub position: Option<String>,
    /// Flow cell id; random when not given.
    #[serde(default)]
    pub flow_cell: Option<String>,
    /// Simulated delay before this run starts.
    #[serde(default = "d_zero")]
    pub start_after: String,
}

fn d_zero() -> String {
    "0s".into()
}

/// `[faults]`
#[derive(Debug, Clone, Default, Deserialize)]
#[serde(deny_unknown_fields, default)]
pub struct Faults {
    /// Stop each run this long after it starts, without a final summary.
    pub abort_after: Option<String>,
    /// Number of closed batch files per run rewritten with new content a minute later.
    pub rewrite_closed: u32,
    /// Number of files per run that appear after the final summary.
    pub late_files: u32,
}

/// A complete scenario.
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Scenario {
    /// Random seed.
    #[serde(default = "d_seed")]
    pub seed: u64,
    /// Simulated hours per run.
    #[serde(default = "d_hours")]
    pub hours: f64,
    /// Simulated seconds per wall-clock second.
    #[serde(default = "d_speed")]
    pub speed: f64,
    /// Content source.
    #[serde(default)]
    pub content: ContentMode,
    /// Timeline source.
    #[serde(default)]
    pub timeline: TimelineMode,
    /// Profile JSON (with `timeline = "profile"`), relative to the scenario file.
    #[serde(default)]
    pub profile: Option<PathBuf>,
    /// How a profile is fitted to `hours`.
    #[serde(default)]
    pub extend: Extend,
    /// `[fake]`
    #[serde(default)]
    pub fake: Fake,
    /// `[replay]`
    #[serde(default)]
    pub replay: Option<Replay>,
    /// `[synthetic]`
    #[serde(default)]
    pub synthetic: Synthetic,
    /// `[[runs]]`
    #[serde(default = "d_runs")]
    pub runs: Vec<RunSpec>,
    /// `[faults]`
    #[serde(default)]
    pub faults: Faults,
}

fn d_seed() -> u64 {
    1
}
fn d_hours() -> f64 {
    2.0
}
fn d_speed() -> f64 {
    1.0
}
fn d_runs() -> Vec<RunSpec> {
    vec![RunSpec {
        experiment: "runsim".into(),
        sample: "sample01".into(),
        position: None,
        flow_cell: None,
        start_after: d_zero(),
    }]
}

/// Typed synthetic parameters.
#[derive(Debug, Clone, Copy)]
pub struct SyntheticParams {
    /// Seconds between batches.
    pub batch_every_s: f64,
    /// pod5 batch bytes.
    pub pod5: u64,
    /// `fastq_pass` batch bytes.
    pub fastq_pass: u64,
    /// `fastq_fail` batch bytes.
    pub fastq_fail: u64,
    /// Barcodes.
    pub barcodes: u32,
}

impl Scenario {
    /// Parse scenario TOML. Relative `profile` and `replay.run` paths are
    /// resolved against `base`.
    ///
    /// # Errors
    /// [`Error::Scenario`] for syntax or validation errors.
    pub fn from_toml(text: &str, base: Option<&Path>) -> Result<Self> {
        let mut s: Self = toml::from_str(text).map_err(|e| Error::Scenario(e.to_string()))?;
        if let Some(base) = base {
            if let Some(p) = s.profile.as_mut() {
                if p.is_relative() {
                    *p = base.join(&*p);
                }
            }
            if let Some(r) = s.replay.as_mut() {
                if r.run.is_relative() {
                    r.run = base.join(&r.run);
                }
            }
        }
        s.validate()?;
        Ok(s)
    }

    /// Load a scenario file.
    ///
    /// # Errors
    /// I/O or scenario errors.
    pub fn load(path: &Path) -> Result<Self> {
        let text = std::fs::read_to_string(path).map_err(io_err("read", path))?;
        Self::from_toml(&text, path.parent())
            .map_err(|e| Error::Scenario(format!("{}: {e}", path.display())))
    }

    /// A built-in preset.
    ///
    /// # Errors
    /// [`Error::Scenario`] for an unknown name.
    pub fn preset(name: &str) -> Result<Self> {
        let text = match name {
            "quick-2h" => include_str!("../presets/quick-2h.toml"),
            "promethion-24h" => include_str!("../presets/promethion-24h.toml"),
            "outage-drill" => include_str!("../presets/outage-drill.toml"),
            other => {
                return Err(Error::Scenario(format!(
                    "unknown preset {other:?}; choose one of {}",
                    crate::PRESETS.join(", ")
                )));
            }
        };
        Self::from_toml(text, None)
    }

    /// Check values and combinations.
    ///
    /// # Errors
    /// [`Error::Scenario`] naming the problem.
    pub fn validate(&self) -> Result<()> {
        let bad = |m: String| Err(Error::Scenario(m));
        if !(self.hours > 0.0 && self.hours <= 24.0 * 60.0) {
            return bad(format!(
                "hours = {} must be more than 0 and at most 1440",
                self.hours
            ));
        }
        if !(self.speed > 0.0 && self.speed <= 1_000_000.0) {
            return bad(format!("speed = {} must be more than 0", self.speed));
        }
        if !(self.fake.size_scale > 0.0 && self.fake.size_scale <= 100.0) {
            return bad(format!(
                "fake.size_scale = {} must be in (0, 100]",
                self.fake.size_scale
            ));
        }
        if self.runs.is_empty() {
            return bad("at least one [[runs]] entry is needed".into());
        }
        for (i, r) in self.runs.iter().enumerate() {
            for (key, v) in [
                ("experiment", Some(&r.experiment)),
                ("sample", Some(&r.sample)),
                ("position", r.position.as_ref()),
                ("flow_cell", r.flow_cell.as_ref()),
            ] {
                if let Some(v) = v {
                    if v.is_empty()
                        || !v
                            .chars()
                            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.'))
                        || v.starts_with('.')
                    {
                        return bad(format!(
                            "runs[{i}].{key} = {v:?}: use letters, digits, '-', '_' and '.' only"
                        ));
                    }
                }
            }
            parse_duration(&r.start_after)
                .map_err(|e| Error::Scenario(format!("runs[{i}].start_after: {e}")))?;
        }
        if self.content == ContentMode::Replay && self.replay.is_none() {
            return bad("content = \"replay\" needs [replay] run = \"<run folder>\"".into());
        }
        if self.timeline == TimelineMode::Profile && self.profile.is_none() {
            return bad("timeline = \"profile\" needs profile = \"<profile.json>\"".into());
        }
        if let Some(a) = &self.faults.abort_after {
            parse_duration(a).map_err(|e| Error::Scenario(format!("faults.abort_after: {e}")))?;
        }
        self.synthetic_params()?;
        Ok(())
    }

    /// Typed `[synthetic]` values.
    ///
    /// # Errors
    /// [`Error::Scenario`] for invalid sizes or durations.
    pub fn synthetic_params(&self) -> Result<SyntheticParams> {
        let s = &self.synthetic;
        let e = |k: &'static str| move |m: String| Error::Scenario(format!("synthetic.{k}: {m}"));
        let every = parse_duration(&s.batch_every).map_err(e("batch_every"))?;
        if every.as_secs_f64() < 1.0 {
            return Err(Error::Scenario(
                "synthetic.batch_every must be at least 1s".into(),
            ));
        }
        if s.barcodes > 96 {
            return Err(Error::Scenario(
                "synthetic.barcodes must be at most 96".into(),
            ));
        }
        Ok(SyntheticParams {
            batch_every_s: every.as_secs_f64(),
            pod5: parse_size(&s.pod5_batch).map_err(e("pod5_batch"))?,
            fastq_pass: parse_size(&s.fastq_pass_batch).map_err(e("fastq_pass_batch"))?,
            fastq_fail: parse_size(&s.fastq_fail_batch).map_err(e("fastq_fail_batch"))?,
            barcodes: s.barcodes,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn presets_load() {
        for name in crate::PRESETS {
            let s = Scenario::preset(name).unwrap();
            assert!(!s.runs.is_empty(), "{name}");
        }
        assert!(Scenario::preset("nope").is_err());
    }

    #[test]
    fn defaults_and_validation() {
        let s = Scenario::from_toml("", None).unwrap();
        assert_eq!((s.hours, s.speed, s.runs.len()), (2.0, 1.0, 1));
        for bad in [
            "hours = 0",
            "speed = -1",
            "content = \"replay\"",
            "timeline = \"profile\"",
            "unknown = 1",
            "[[runs]]\nexperiment = \"../x\"\nsample = \"s\"",
            "[synthetic]\nbatch_every = \"0s\"",
            "[faults]\nabort_after = \"soon\"",
        ] {
            assert!(Scenario::from_toml(bad, None).is_err(), "{bad}");
        }
    }
}
